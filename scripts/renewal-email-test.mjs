import assert from 'node:assert/strict';
import {reminderSettings, reminderItems, reminderText, recipientItems, reminderHtml} from '../renewal-email.mjs';
const settings = {renewalAssignments:[{email:'Test@example.com',facilities:['Bronx Center']},{email:'test@example.com',facilities:['Brooklyn Center']}], renewalAppUrl:'https://contracts.example.com/', alertSchedule:'90,60,30'};
assert.equal(reminderSettings(settings).enabled, false);
assert.equal(reminderSettings(settings).recipients.length, 1);
assert.throws(() => reminderSettings({...settings, renewalAssignments:[{email:'bad',facilities:['Bronx Center']}]}));
assert.throws(() => reminderSettings({renewalEmailEnabled:true}));
const alerts = [91,90,61,60,31,30,0,-1].map(days => ({contractId:'id /?',days,targetDate:'2026-12-01',alertBasis:'Notice deadline'}));
const items = reminderItems(alerts, settings);
assert.deepEqual(items.map(x=>x.window),[90,90,60,60,30,30]);
assert.match(items[0].link,/contract=id%20%2F%3F/);
assert.notEqual(items[0].key,reminderItems([{...alerts[1],targetDate:'2027-12-01'}],settings)[0].key);
assert.match(reminderText(items),/Notice deadline/);
console.log('Renewal email boundaries, recipients, links, and delivery keys passed.');
const scoped = [{facility:'Bronx Center'}, {facility:'Brooklyn Center'}, {facility:'Other'}];
assert.equal(recipientItems(scoped,settings,'test@example.com').length,2);
assert.equal(recipientItems(scoped,settings,'unassigned@example.com').length,0);
assert.equal(recipientItems(scoped,{...settings,renewalAssignments:[]},'test@example.com').length,0);
assert.throws(()=>reminderSettings({...settings,renewalAssignments:[{email:'test@example.com',facilities:[]}]}));
const html = reminderHtml([{...items[0],contractName:'<script>bad</script>',vendor:'A & B'}]);
assert.ok(!html.includes('<script>'));
assert.ok(html.includes('&lt;script&gt;'));
assert.ok(!html.includes('view=vendor'));
assert.ok(html.includes('Open Contract') && !html.includes('View Vendor'));
assert.equal((html.match(/<a /g) || []).length, 1);
assert.ok(html.includes(items[0].link.replaceAll('&', '&amp;')));
console.log('Facility isolation, escaping, and single contract link passed.');
assert.ok(html.includes('font-size:16px'));
assert.ok(!html.includes('background:#2f267f;border:1px'));
const unconfirmed = reminderHtml([{...items[0],vendor:'Needs Classification'}]);
assert.ok(!unconfirmed.includes('View Vendor'));
assert.ok(unconfirmed.includes('Open Contract'));
